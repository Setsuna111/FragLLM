def normalize_text(text: str) -> str:
    text = str(text).strip()
    text = re.sub(r"<\|.*?\|>", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def extract_pred_class(text: str) -> str:
    text = normalize_text(text)
    patterns = [
        r"^It is the (.*?)[\.\n]*$",
        r"^The category is (.*?)[\.\n]*$",
        r"^This belongs to the (.*?)[\.\n]*$",
        r"^It is categorized as (.*?)[\.\n]*$",
        r"^This instance is identified as (.*?)[\.\n]*$",
        r"^The determined class is (.*?)[\.\n]*$",
        r"^It has been assigned to the (.*?) group[\.\n]*$",
        r"^It is grouped under the (.*?) category[\.\n]*$",
        r"^The appropriate category for this is (.*?)[\.\n]*$",
        r"^Its class designation is (.*?)[\.\n]*$",
    ]
    for pattern in patterns:
        match = re.match(pattern, text, flags=re.IGNORECASE)
        if match:
            return match.group(1).strip(" .")
    return text.strip(" .")


def compute_iou(pred: Tuple[int, int], ref: Tuple[int, int]) -> float:
    pred_start, pred_end = pred
    ref_start, ref_end = ref
    inter_left = max(pred_start, ref_start)
    inter_right = min(pred_end, ref_end)
    intersection = max(0, inter_right - inter_left + 1)
    union_left = min(pred_start, ref_start)
    union_right = max(pred_end, ref_end)
    union = max(0, union_right - union_left + 1)
    return intersection / union if union > 0 else 0.0


def interval_intersection_union(pred: Tuple[int, int], ref: Tuple[int, int]) -> Tuple[int, int]:
    inter_left = max(pred[0], ref[0])
    inter_right = min(pred[1], ref[1])
    intersection = max(0, inter_right - inter_left + 1)
    union_left = min(pred[0], ref[0])
    union_right = max(pred[1], ref[1])
    union = max(0, union_right - union_left + 1)
    return intersection, union


def interval_length(position: Tuple[int, int]) -> int:
    return max(0, int(position[1]) - int(position[0]) + 1)


def interval_intersection_length(left: Tuple[int, int], right: Tuple[int, int]) -> int:
    start = max(int(left[0]), int(right[0]))
    end = min(int(left[1]), int(right[1]))
    return max(0, end - start + 1)


def merge_intervals(intervals: List[Tuple[int, int]]) -> List[Tuple[int, int]]:
    if not intervals:
        return []
    sorted_intervals = sorted((int(s), int(e)) for s, e in intervals if int(e) >= int(s))
    merged = [sorted_intervals[0]]
    for start, end in sorted_intervals[1:]:
        last_start, last_end = merged[-1]
        if start <= last_end + 1:
            merged[-1] = (last_start, max(last_end, end))
        else:
            merged.append((start, end))
    return merged


def intervals_total_length(intervals: List[Tuple[int, int]]) -> int:
    return sum(interval_length(interval) for interval in merge_intervals(intervals))


def intervals_intersection_length(
    left_intervals: List[Tuple[int, int]],
    right_intervals: List[Tuple[int, int]],
) -> int:
    left_merged = merge_intervals(left_intervals)
    right_merged = merge_intervals(right_intervals)
    left_idx = 0
    right_idx = 0
    total = 0
    while left_idx < len(left_merged) and right_idx < len(right_merged):
        left = left_merged[left_idx]
        right = right_merged[right_idx]
        total += interval_intersection_length(left, right)
        if left[1] < right[1]:
            left_idx += 1
        else:
            right_idx += 1
    return total


def label_residue_intersection_union(
    pred_by_label: Dict[str, List[Tuple[int, int]]],
    ref_by_label: Dict[str, List[Tuple[int, int]]],
) -> Tuple[int, int]:
    labels = set(pred_by_label.keys()) | set(ref_by_label.keys())
    intersection = 0
    union = 0
    for label in labels:
        pred_intervals = pred_by_label.get(label, [])
        ref_intervals = ref_by_label.get(label, [])
        label_intersection = intervals_intersection_length(pred_intervals, ref_intervals)
        label_pred_len = intervals_total_length(pred_intervals)
        label_ref_len = intervals_total_length(ref_intervals)
        intersection += label_intersection
        union += label_pred_len + label_ref_len - label_intersection
    return intersection, union


def greedy_match(
    pred_positions: List[Tuple[int, int]],
    ref_positions: List[Tuple[int, int]],
) -> List[Tuple[int, int, float]]:
    if not pred_positions or not ref_positions:
        return []
    candidates = []
    for pred_idx, pred_pos in enumerate(pred_positions):
        for ref_idx, ref_pos in enumerate(ref_positions):
            iou = compute_iou(pred_pos, ref_pos)
            if iou > 0:
                candidates.append((iou, pred_idx, ref_idx))
    candidates.sort(reverse=True)
    used_pred = set()
    used_ref = set()
    matches = []
    for iou, pred_idx, ref_idx in candidates:
        if pred_idx in used_pred or ref_idx in used_ref:
            continue
        used_pred.add(pred_idx)
        used_ref.add(ref_idx)
        matches.append((pred_idx, ref_idx, iou))
    return matches


def load_filtered_group_ground_truth(
    root_dir: str,
    dataset_name: str,
    split: str,
    max_sequence_length: int,
) -> Dict[int, Dict]:
    data_name = DATASET_TO_DATA_NAME[dataset_name]
    source_path = os.path.join(root_dir, data_name, f"{split}.json")
    with open(source_path, "r", encoding="utf-8") as f:
        samples = json.load(f)

    data_by_idx = {}
    dataset_idx = 0
    for item in samples:
        if item.get("completeness") == "no":
            continue
        starts = []
        ends = []
        for fragment_group in item.get("fragments", []):
            starts.extend(frag["start_position"] for frag in fragment_group.get("frags", []))
            ends.extend(frag["end_position"] for frag in fragment_group.get("frags", []))
        if not starts:
            continue
        if max(ends) - min(starts) + 1 > max_sequence_length:
            continue

        fragments = []
        for fragment_group in item["fragments"]:
            for frag in fragment_group["frags"]:
                fragments.append(
                    {
                        "uid": item["uid"],
                        "interpro_id": fragment_group["interpro_id"],
                        "category": fragment_group["category"],
                        "description": fragment_group.get("description", ""),
                        "start_pos": int(frag["start_position"]),
                        "end_pos": int(frag["end_position"]),
                    }
                )
        data_by_idx[dataset_idx] = {
            "uid": item["uid"],
            "sequence_length": len(item["sequence"]),
            "fragments": fragments,
        }
        dataset_idx += 1
    return data_by_idx


class InterProRetriever:
    def __init__(
        self,
        embedding_model: str,
        interpro_db_path: str,
        cache_dir: str,
        batch_size: int,
        device: str,
    ):
        self.embedding_model_name = embedding_model
        self.interpro_db_path = interpro_db_path
        self.cache_dir = cache_dir
        self.batch_size = batch_size
        self.device = device if torch.cuda.is_available() and device.startswith("cuda") else "cpu"
        self.model = SentenceTransformer(embedding_model)
        self.model = self.model.to(self.device)
        self.interpro_ids, self.categories, self.embeddings = self._load_or_create_cache()

    def _cache_path(self):
        os.makedirs(self.cache_dir, exist_ok=True)
        model_key = self.embedding_model_name.strip("/").replace("/", "_")
        db_key = os.path.splitext(os.path.basename(self.interpro_db_path))[0]
        return os.path.join(self.cache_dir, f"interpro_category_embeddings_{db_key}_{model_key}.pkl")

    def _load_interpro_entries(self):
        with open(self.interpro_db_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        interpro_ids = []
        categories = []
        for interpro_id, entry in data.items():
            category = entry.get("category")
            if not category:
                continue
            interpro_ids.append(interpro_id)
            categories.append(category)
        return interpro_ids, categories

    def _encode(self, texts: List[str]) -> np.ndarray:
        embeddings = self.model.encode(
            texts,
            batch_size=self.batch_size,
            convert_to_numpy=True,
            show_progress_bar=True,
            normalize_embeddings=True,
        )
        return embeddings

    def _load_or_create_cache(self):
        cache_path = self._cache_path()
        if os.path.exists(cache_path):
            with open(cache_path, "rb") as f:
                cache = pickle.load(f)
            return cache["interpro_ids"], cache["categories"], cache["embeddings"]

        interpro_ids, categories = self._load_interpro_entries()
        embeddings = self._encode(categories)
        with open(cache_path, "wb") as f:
            pickle.dump(
                {
                    "interpro_ids": interpro_ids,
                    "categories": categories,
                    "embeddings": embeddings,
                },
                f,
            )
        return interpro_ids, categories, embeddings

    def predict(self, texts: List[str]) -> Tuple[List[str], List[str], List[float]]:
        if not texts:
            return [], [], []
        pred_embeddings = self._encode([extract_pred_class(text) for text in texts])
        scores = np.matmul(pred_embeddings, self.embeddings.T)
        best = np.argmax(scores, axis=1)
        return (
            [self.interpro_ids[i] for i in best],
            [self.categories[i] for i in best],
            [float(scores[row_idx, col_idx]) for row_idx, col_idx in enumerate(best)],
        )


def safe_div(num: float, den: float) -> float:
    return float(num / den) if den else 0.0


def evaluate(args) -> Dict:
    pred_df = pd.read_csv(args.results_path)
    if pred_df.empty:
        raise ValueError(f"No predictions found in {args.results_path}")
    if "dataset_name" not in pred_df.columns:
        raise ValueError("Prediction CSV must include dataset_name column")
    dataset_names = sorted(pred_df["dataset_name"].dropna().unique().tolist())
    if len(dataset_names) != 1:
        raise ValueError(
            "This metric script expects one dataset per CSV. "
            f"Found dataset_name values: {dataset_names}"
        )
    dataset_name = dataset_names[0]
    if dataset_name not in DATASET_TO_DATA_NAME:
        raise ValueError(f"Unsupported dataset: {dataset_name}")

    retriever = InterProRetriever(
        embedding_model=args.embedding_model,
        interpro_db_path=args.interpro_db_path,
        cache_dir=args.cache_dir,
        batch_size=args.batch_size,
        device=args.device,
    )
    pred_texts = pred_df["pred_cls"].fillna("").astype(str).tolist()
    pred_interpro_ids, pred_categories, pred_scores = retriever.predict(pred_texts)
    pred_df["pred_interpro_id"] = pred_interpro_ids
    pred_df["pred_category_retrieved"] = pred_categories
    pred_df["pred_category_score"] = pred_scores

    truth_by_idx = load_filtered_group_ground_truth(
        root_dir=args.root_dir,
        dataset_name=dataset_name,
        split=args.split,
        max_sequence_length=args.max_sequence_length,
    )  # 得到预测csv中每一行的label后，需要在集合到蛋白上。再load group grounding dataset提取true样本

    pred_count = int(len(pred_df))
    ref_count = int(sum(len(item["fragments"]) for item in truth_by_idx.values()))
    position_tp = 0
    joint_tp = 0
    matched_iou_sum = 0.0
    matched_distance_sum = 0.0
    matched_count = 0
    global_intersection = 0
    global_union = 0
    residue_level_intersection = 0
    residue_level_union = 0
    protein_residue_ious = []
    matched_rows = []

    for dataset_idx, group_df in pred_df.groupby("dataset_idx", sort=False):
        dataset_idx = int(dataset_idx)  # 注意这里dataset idx是实现group grounding推理时就存在的一个东西, 后面再进行ref cls的时候, 才会讲每一行的分多行拆开来存, 但是共享这个idx
        truth_item = truth_by_idx.get(dataset_idx, {"fragments": []})
        ref_fragments = truth_item["fragments"]
        pred_positions = [
            (int(row.start_pos), int(row.end_pos))
            for row in group_df.itertuples(index=False)
        ]
        ref_positions = [
            (int(fragment["start_pos"]), int(fragment["end_pos"]))
            for fragment in ref_fragments
        ]
        pred_original_indices = group_df.index.tolist()
        pred_by_label = {}
        for pred_local_idx, pred_pos in enumerate(pred_positions):
            pred_global_idx = pred_original_indices[pred_local_idx]
            pred_label = pred_df.loc[pred_global_idx, "pred_interpro_id"]
            pred_by_label.setdefault(pred_label, []).append(pred_pos)
        ref_by_label = {}
        for ref_fragment, ref_pos in zip(ref_fragments, ref_positions):
            ref_by_label.setdefault(ref_fragment["interpro_id"], []).append(ref_pos)
        protein_intersection, protein_union = label_residue_intersection_union(
            pred_by_label, ref_by_label
        )
        residue_level_intersection += protein_intersection
        residue_level_union += protein_union
        protein_residue_ious.append(safe_div(protein_intersection, protein_union))

        matches = greedy_match(pred_positions, ref_positions)
        for pred_local_idx, ref_idx, iou in matches:
            pred_global_idx = pred_original_indices[pred_local_idx]
            ref_fragment = ref_fragments[ref_idx]
            pred_pos = pred_positions[pred_local_idx]
            ref_pos = ref_positions[ref_idx]
            intersection, union = interval_intersection_union(pred_pos, ref_pos)
            global_intersection += intersection
            global_union += union
            matched_iou_sum += iou
            matched_distance_sum += abs(pred_pos[0] - ref_pos[0]) + abs(pred_pos[1] - ref_pos[1])
            matched_count += 1
            position_correct = iou >= args.iou_threshold
            class_correct = pred_df.loc[pred_global_idx, "pred_interpro_id"] == ref_fragment["interpro_id"]
            if position_correct:
                position_tp += 1
                if class_correct:
                    joint_tp += 1
            matched_rows.append(
                {
                    "dataset_idx": dataset_idx,
                    "uid": ref_fragment["uid"],
                    "pred_row_index": int(pred_global_idx),
                    "pred_start_pos": pred_pos[0],
                    "pred_end_pos": pred_pos[1],
                    "ref_start_pos": ref_pos[0],
                    "ref_end_pos": ref_pos[1],
                    "iou": iou,
                    "position_correct": position_correct,
                    "pred_interpro_id": pred_df.loc[pred_global_idx, "pred_interpro_id"],
                    "pred_category_retrieved": pred_df.loc[pred_global_idx, "pred_category_retrieved"],
                    "pred_category_score": float(pred_df.loc[pred_global_idx, "pred_category_score"]),
                    "ref_interpro_id": ref_fragment["interpro_id"],
                    "ref_category": ref_fragment["category"],
                    "class_correct": class_correct,
                    "joint_correct": bool(position_correct and class_correct),
                }
            )

    position_precision = safe_div(position_tp, pred_count)
    position_recall = safe_div(position_tp, ref_count)
    position_f1 = safe_div(
        2 * position_precision * position_recall,
        position_precision + position_recall,
    )
    class_precision = safe_div(joint_tp, pred_count)
    class_recall = safe_div(joint_tp, ref_count)
    class_f1 = safe_div(2 * class_precision * class_recall, class_precision + class_recall)

    results = {
        "dataset_name": dataset_name,
        "pred_fragments": pred_count,
        "ref_fragments": ref_count,
        "matched_pairs": matched_count,
        "position_tp": position_tp,
        "joint_cls_position_tp": joint_tp,
        "residue_level_iou": safe_div(residue_level_intersection, residue_level_union),
        "avg_protein_residue_level_iou": safe_div(sum(protein_residue_ious), len(protein_residue_ious)),
        "residue_level_intersection": residue_level_intersection,
        "residue_level_union": residue_level_union,
        "avg_iou_matched": safe_div(matched_iou_sum, matched_count),
        "global_iou_matched": safe_div(global_intersection, global_union),
        "avg_distance_matched": safe_div(matched_distance_sum, matched_count),
        "global_position_recall": position_recall,
        "global_position_precision": position_precision,
        "global_position_f1": position_f1,
        "global_class_recall": class_recall,
        "global_class_precision": class_precision,
        "global_class_f1": class_f1,
    }

    annotated_path = args.results_path.replace(".csv", "_with_retrieved_cls.csv")
    pred_df.to_csv(annotated_path, index=False)
    matches_path = args.results_path.replace(".csv", "_matched_pairs.csv")
    pd.DataFrame(matched_rows).to_csv(matches_path, index=False)
    metrics_path = args.results_path.replace(".csv", "_comprehensive_metrics.json")
    with open(metrics_path, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)

    print(f"Saved annotated predictions to {annotated_path}")
    print(f"Saved matched pairs to {matches_path}")
    print(f"Saved metrics to {metrics_path}")
    for key, value in results.items():
        print(f"{key}: {value}")
    return results


if __name__ == "__main__":
    evaluate(parse_args())
